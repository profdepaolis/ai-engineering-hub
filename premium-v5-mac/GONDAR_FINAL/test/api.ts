import assert from 'node:assert/strict';
import * as api from '../src/premium-v5/index';
import {sampleMotion} from '../src/v3/motion';
const required=['TypingCamera','AnimatedUnderline','PhotoMotionShutter','CinematicReveal','CinematicImpact','DirectionalHandoff','BakedJacket3D','CinematicGlobe','AnimatedSearch','SoundDesignTrack'] as const;
for (const name of required) assert.equal(typeof api[name], 'function', `Export mancante: ${name}`);
const director:api.Director={fps:30,durationInFrames:120,sampleRate:48000,events:[{id:'a',frame:10},{id:'b',frame:30}]};
assert.equal(api.productionMode('regia-completa'),'REGIA COMPLETA');
assert.equal(api.frameOf(director,{id:'b',offset:2}),32);
assert.throws(()=>api.frameOf(director,'assente'));
assert.deepEqual(api.bindMotion(director,[{at:'a',x:0},{at:'b',x:100}]).map(k=>k.frame),[10,30]);
assert.throws(()=>api.bindMotion(director,[{at:'b',x:0},{at:'a',x:1}]));
const glyphs:api.Glyph[]=[{char:'K',cue:'a',word:0,line:0,x:0,width:20},{char:'O',cue:'b',word:0,line:0,x:20,width:20}];
assert.equal(api.visibleGlyphs(director,glyphs,29).length,1);
assert.equal(api.glyphRangeProgress(director,glyphs,40,0,1).progress,1);
assert.equal(api.sourceTurnFrame(20,10,30,100,200),150);
assert.equal(api.routeProgress(30,20,30),1);
assert.ok(Math.abs(Math.hypot(...api.latLonXYZ(40,16))-2)<1e-9);
assert.equal(api.auditDirector(director).passed,true);
assert.equal(api.auditDirector({...director,events:[...director.events,{id:'a',frame:150}]}).passed,false);
const pose=sampleMotion([{frame:0,x:0},{frame:10,x:100}],5); assert.ok(pose.x>0 && pose.x<100);
console.log('OK: 10 export V5, cue, testo, movimento, globo e verifiche numeriche.');
console.log('Nessun rendering o accesso alle bozze KORA eseguito.');
